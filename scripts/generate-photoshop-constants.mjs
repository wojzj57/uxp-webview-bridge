import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(
  repoRoot,
  "src",
  "shared",
  "types",
  "photoshop",
  "internal",
  "dom",
  "Constants.d.ts"
);
const outputPath = path.join(repoRoot, "src", "shared", "photoshop-api", "photoshop-constants.ts");
const checkOnly = process.argv.includes("--check");

const sourceText = await readFile(sourcePath, "utf8");
const sourceFile = ts.createSourceFile(sourcePath, sourceText, ts.ScriptTarget.Latest, true);
const enums = sourceFile.statements.filter(ts.isEnumDeclaration).map(readEnum);
const output = render(enums);

if (checkOnly) {
  const current = await readFile(outputPath, "utf8");
  if (current !== output) {
    console.error(
      "Generated Photoshop constants are stale. Run `pnpm generate:photoshop-constants` and commit the result."
    );
    process.exit(1);
  }
  console.log(`Verified ${enums.length} generated Photoshop enum tables.`);
} else {
  await writeFile(outputPath, output, "utf8");
  console.log(`Generated ${enums.length} Photoshop enum tables at ${path.relative(repoRoot, outputPath)}.`);
}

function readEnum(node) {
  return {
    name: node.name.text,
    members: node.members.map((member) => ({
      name: readMemberName(member.name),
      value: readInitializer(member.initializer, node.name.text, readMemberName(member.name))
    }))
  };
}

function readMemberName(node) {
  if (ts.isIdentifier(node) || ts.isStringLiteral(node) || ts.isNumericLiteral(node)) {
    return node.text;
  }
  throw new Error(`Unsupported Photoshop enum member name: ${node.getText(sourceFile)}`);
}

function readInitializer(node, enumName, memberName) {
  if (ts.isStringLiteral(node)) {
    return node.text;
  }
  if (ts.isNumericLiteral(node)) {
    return Number(node.text);
  }
  throw new Error(
    `Unsupported Photoshop enum initializer for ${enumName}.${memberName}: ${node?.getText(sourceFile) ?? "missing"}`
  );
}

function render(enums) {
  const sections = enums.map(({ name, members }) => {
    const lines = members.map(({ name: memberName, value }) =>
      `  ${renderPropertyName(memberName)}: ${JSON.stringify(value)}`
    );
    return [
      `/** Runtime values for Adobe Photoshop's \`${name}\` enum. */`,
      `export const ${name} = {`,
      lines.join(",\n"),
      `} as const;`,
      `export type ${name}Value = (typeof ${name})[keyof typeof ${name}];`
    ].join("\n");
  });

  return [
    "/**",
    " * Photoshop DOM enum values as synchronous, transport-safe runtime objects.",
    " *",
    " * Generated by `scripts/generate-photoshop-constants.mjs` from",
    " * `src/shared/types/photoshop/internal/dom/Constants.d.ts`. Do not edit by hand.",
    " */",
    "",
    sections.join("\n\n"),
    "",
    "/** Every Photoshop constants table, exposed synchronously by the WebView namespace. */",
    "export const PhotoshopConstants = {",
    enums.map(({ name }) => `  ${name}`).join(",\n"),
    "} as const;",
    "",
    "export type PhotoshopConstantsNamespace = typeof PhotoshopConstants;",
    ""
  ].join("\n");
}

function renderPropertyName(name) {
  return /^[$A-Z_a-z][$\w]*$/.test(name) ? name : JSON.stringify(name);
}
