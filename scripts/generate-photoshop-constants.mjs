import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceSpecs = [
  {
    path: path.join(
      repoRoot,
      "src",
      "shared",
      "types",
      "photoshop",
      "internal",
      "dom",
      "Constants.d.ts"
    )
  },
  {
    path: path.join(
      repoRoot,
      "src",
      "shared",
      "types",
      "photoshop",
      "internal",
      "dom",
      "Layer.d.ts"
    ),
    enumNames: ["PSLayerKind"]
  }
];
const outputPath = path.join(repoRoot, "src", "shared", "photoshop-api", "photoshop-constants.ts");
const checkOnly = process.argv.includes("--check");

const sources = await Promise.all(
  sourceSpecs.map(async (spec) => {
    const sourceText = await readFile(spec.path, "utf8");
    return {
      ...spec,
      sourceFile: ts.createSourceFile(spec.path, sourceText, ts.ScriptTarget.Latest, true)
    };
  })
);
const enums = collectEnums(sources);
const output = render(enums, sources);

if (checkOnly) {
  const current = await readFile(outputPath, "utf8");
  if (current !== output) {
    console.error(
      "Generated Photoshop constants are stale. Run `pnpm generate:photoshop-constants` and commit the result."
    );
    process.exit(1);
  }
  console.log(`Verified ${enums.length} generated Photoshop enum tables.`);
} else {
  await writeFile(outputPath, output, "utf8");
  console.log(`Generated ${enums.length} Photoshop enum tables at ${path.relative(repoRoot, outputPath)}.`);
}

function collectEnums(sources) {
  const collected = [];
  const seen = new Map();

  for (const { path: sourcePath, enumNames, sourceFile } of sources) {
    const declarations = sourceFile.statements.filter(ts.isEnumDeclaration);
    const selected = enumNames
      ? enumNames.flatMap((enumName) => {
          const matches = declarations.filter((node) => node.name.text === enumName);
          if (matches.length !== 1) {
            throw new Error(
              `Expected exactly one selected Photoshop enum ${enumName} in ${relativePath(sourcePath)}, found ${matches.length}.`
            );
          }
          return matches;
        })
      : declarations;

    for (const node of selected) {
      const name = node.name.text;
      const previousSource = seen.get(name);
      if (previousSource) {
        throw new Error(
          `Duplicate Photoshop enum ${name} selected from ${relativePath(previousSource)} and ${relativePath(sourcePath)}.`
        );
      }
      seen.set(name, sourcePath);
      collected.push(readEnum(node, sourceFile, sourcePath));
    }
  }

  return collected;
}

function readEnum(node, sourceFile, sourcePath) {
  return {
    name: node.name.text,
    members: node.members.map((member) => {
      const name = readMemberName(member.name, node.name.text, sourceFile, sourcePath);
      return {
        name,
        value: readInitializer(member.initializer, node.name.text, name, sourceFile, sourcePath)
      };
    })
  };
}

function readMemberName(node, enumName, sourceFile, sourcePath) {
  if (ts.isIdentifier(node) || ts.isStringLiteral(node) || ts.isNumericLiteral(node)) {
    return node.text;
  }
  throw new Error(
    `Unsupported Photoshop enum member name in ${relativePath(sourcePath)} for ${enumName}: ${node.getText(sourceFile)}`
  );
}

function readInitializer(node, enumName, memberName, sourceFile, sourcePath) {
  if (ts.isStringLiteral(node)) {
    return node.text;
  }
  if (ts.isNumericLiteral(node)) {
    return Number(node.text);
  }
  throw new Error(
    `Unsupported Photoshop enum initializer in ${relativePath(sourcePath)} for ${enumName}.${memberName}: ${node?.getText(sourceFile) ?? "missing"}`
  );
}

function render(enums, sources) {
  const sections = enums.map(({ name, members }) => {
    const lines = members.map(({ name: memberName, value }) =>
      `  ${renderPropertyName(memberName)}: ${JSON.stringify(value)}`
    );
    return [
      `/** Runtime values for Adobe Photoshop's \`${name}\` enum. */`,
      `export const ${name} = {`,
      lines.join(",\n"),
      `} as const;`,
      `export type ${name}Value = (typeof ${name})[keyof typeof ${name}];`
    ].join("\n");
  });

  return [
    "/**",
    " * Photoshop DOM enum values as synchronous, transport-safe runtime objects.",
    " *",
    " * Generated by `scripts/generate-photoshop-constants.mjs` from",
    ...sources.map(({ path: sourcePath }) => ` * \`${relativePath(sourcePath)}\``),
    " * Do not edit by hand.",
    " */",
    "",
    sections.join("\n\n"),
    "",
    "/** Every Photoshop constants table, exposed synchronously by the WebView namespace. */",
    "export const PhotoshopConstants = {",
    enums.map(({ name }) => `  ${name}`).join(",\n"),
    "} as const;",
    "",
    "export type PhotoshopConstantsNamespace = typeof PhotoshopConstants;",
    ""
  ].join("\n");
}

function renderPropertyName(name) {
  return /^[$A-Z_a-z][$\w]*$/.test(name) ? name : JSON.stringify(name);
}

function relativePath(filePath) {
  return path.relative(repoRoot, filePath).replaceAll(path.sep, "/");
}
